# shellcheck shell=bash
# Termux host helpers. Sourced by bin/andlinux after lib/common.sh.

AL_CONFIG_DIR=${AL_CONFIG_DIR:-$HOME/.config/andlinux}
AL_STATE_DIR=${AL_STATE_DIR:-$HOME/.local/state/andlinux}
AL_USER_CONFIG=$AL_CONFIG_DIR/config.env
AL_GUEST_CONFIG=$AL_STATE_DIR/guest-config.env

al_is_termux() {
  [[ -n "${PREFIX:-}" && "$PREFIX" == */com.termux/files/usr ]]
}

al_load_config() {
  al_load_env "$AL_ROOT/config/defaults.env"
  al_load_env "$AL_USER_CONFIG"
  : "${AL_IMAGE:=}"
  if [[ -z "$AL_IMAGE" ]]; then
    AL_IMAGE="ubuntu:${AL_UBUNTU_RELEASE}"
  fi
  if [[ -z "${AL_TZ:-}" ]]; then
    AL_TZ=$(al_android_prop persist.sys.timezone)
    : "${AL_TZ:=Asia/Seoul}"
  fi
  export AL_IMAGE AL_TZ
}

# al_android_prop NAME : print an Android system property, or nothing.
al_android_prop() {
  if [[ -x /system/bin/getprop ]]; then
    /system/bin/getprop "$1" 2>/dev/null || true
  fi
}

# al_pkg_update : refresh Termux package lists. pkg picks a random community
# mirror; when that one is broken (stale, missing an architecture, offline),
# pin the official default mirror the way termux-change-repo does and retry.
al_pkg_update() {
  timeout 600 pkg update -y && return 0
  local chosen=$PREFIX/etc/termux/chosen_mirrors
  if [[ -f "$PREFIX/etc/termux/mirrors/default" && ! -e "$chosen" ]]; then
    al_warn "Termux mirror failed; switching to the official default mirror"
    al_warn "(pick another later with: termux-change-repo)"
    ln -sfn "$PREFIX/etc/termux/mirrors/default" "$chosen"
  fi
  al_retry 3 timeout 600 pkg --check-mirror update -y
}

al_rootfs() {
  printf '%s/var/lib/proot-distro/containers/%s/rootfs' "$PREFIX" "$AL_CONTAINER"
}

al_container_exists() {
  proot-distro list -q 2>/dev/null | grep -qx "$AL_CONTAINER"
}

al_proot_distro_version() {
  dpkg-query -W -f='${Version}' proot-distro 2>/dev/null || true
}

# Environment forwarded into every guest session. proot-distro starts the guest
# with an empty environment, so Termux:API helpers (am, termux-*), proxies and
# locale/timezone would otherwise be lost.
al_guest_env_args() {
  local -a args=()
  local var
  for var in ANDROID_ART_ROOT ANDROID_DATA ANDROID_I18N_ROOT ANDROID_ROOT \
    ANDROID_RUNTIME_ROOT ANDROID_TZDATA_ROOT BOOTCLASSPATH \
    DEX2OATBOOTCLASSPATH SYSTEMSERVERCLASSPATH EXTERNAL_STORAGE \
    TERMUX_VERSION TERMUX_APK_RELEASE TERMUX_APP__PACKAGE_NAME \
    HTTPS_PROXY HTTP_PROXY NO_PROXY https_proxy http_proxy no_proxy \
    COLORTERM; do
    if [[ -n "${!var:-}" ]]; then
      args+=(-e "$var=${!var}")
    fi
  done
  args+=(-e "TERMUX_PREFIX=$PREFIX" -e "TERMUX_HOME=$HOME")
  args+=(-e "TZ=$AL_TZ" -e "LANG=$AL_LANG")
  printf '%s\0' "${args[@]}"
}

# al_login [--root] [--detach] [extra proot-distro login options] -- CMD...
# Every session shares Termux's /tmp so the X11 socket, the virgl socket and
# files under /tmp look the same from CLI, desktop and service sessions.
al_login() {
  local -a opts=(--shared-tmp) env_args=()
  local user=$AL_USER
  while (($#)); do
    case $1 in
      --root) user=root ;;
      --detach) opts+=(-d) ;;
      --) shift; break ;;
      *) opts+=("$1") ;;
    esac
    shift
  done
  mapfile -d '' env_args < <(al_guest_env_args)
  if [[ "$user" != root ]]; then
    opts+=(--user "$AL_USER" -w "/home/$AL_USER")
  fi
  if (($#)); then
    proot-distro login "${opts[@]}" "${env_args[@]}" "$AL_CONTAINER" -- "$@"
  else
    proot-distro login "${opts[@]}" "${env_args[@]}" "$AL_CONTAINER"
  fi
}

# al_config_set KEY VALUE : persist an override in the user config file.
al_config_set() {
  local key=$1 value=$2 tmp
  [[ "$key" =~ ^AL_[A-Z0-9_]+$ ]] || al_die "invalid config key '$key'"
  mkdir -p "$AL_CONFIG_DIR"
  touch "$AL_USER_CONFIG"
  tmp=$(mktemp)
  grep -v "^${key}=" "$AL_USER_CONFIG" >"$tmp" || true
  printf '%s=%q\n' "$key" "$value" >>"$tmp"
  cat "$tmp" >"$AL_USER_CONFIG"
  rm -f "$tmp"
  printf -v "$key" '%s' "$value"
  export "${key?}"
}

al_require_container() {
  al_container_exists || al_die "container '$AL_CONTAINER' is not installed; run: andlinux setup"
}

al_write_guest_config() {
  local var
  mkdir -p "$AL_STATE_DIR"
  {
    echo "# Generated by andlinux on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not edit;"
    echo "# change ~/.config/andlinux/config.env in Termux and rerun setup."
    while IFS= read -r var; do
      printf '%s=%q\n' "$var" "${!var}"
    done < <(compgen -v AL_ | grep -vE '^AL_(ROOT|CONFIG_DIR|STATE_DIR|USER_CONFIG|GUEST_CONFIG)$' | sort)
    printf 'AL_TERMUX_ROOT=%q\n' "$AL_ROOT"
  } >"$AL_GUEST_CONFIG"
}
